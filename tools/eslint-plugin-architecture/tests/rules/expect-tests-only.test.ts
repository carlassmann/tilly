import { ruleTester } from "../rule-tester.js"
import rule from "../../rules/expect-tests-only.js"

function invalid(messageId: string, codes: string[]) {
	return codes.map(code => ({ name: code, code, errors: [{ messageId }] }))
}

// No type information: the rule also runs on ordinary source files.
ruleTester.run("expect-tests-only", rule, {
	valid: [
		`expect(summary).toMatchInlineSnapshot()`,
		`expect(summary).toMatchInlineSnapshot(\`"Ada"\`)`,
		`expect(summary).toMatchInlineSnapshot('"Ada"')`,
		`expect(() => parse("")).toThrow("empty")`,
		`expect(() => parse("")).toThrowError(/empty/)`,
		`expect(() => parse("")).toThrowErrorMatchingInlineSnapshot()`,
		`expect(() => parse("")).toThrowErrorMatchingInlineSnapshot(\`[Error: empty]\`)`,
		`await expect(load()).rejects.toThrow("missing")`,
		`await expect(load()).resolves.toMatchInlineSnapshot()`,
		`expect.soft(summary).toMatchInlineSnapshot()`,
		`await expect.poll(() => count).toMatchInlineSnapshot()`,
		`expect(summary)["toMatchInlineSnapshot"]()`,
		`expect.hasAssertions()`,
		`expect.assertions(2)`,
		`import { describe, it, expect, vi, beforeEach } from "vitest"`,
		`import type { Mock } from "vitest"`,
		`import { type Mock, test } from "vitest"`,
		`import { expect as check } from "vitest"; check(1).toMatchInlineSnapshot()`,
		`import { expectTypeOf, assertType } from "vitest"; expectTypeOf(1).toEqualTypeOf<number>(); assertType<number>(1)`,
		`type Expect = typeof expect`,
		`await import("./module.js")`,
		`await vi.importActual("#shared/lib/dates")`,
		`let context = { expected: 1 }; context.expected`,
		{
			name: "a local function named expect is not vitest's",
			code: `function expect(value: number) { return value }; expect(1).toBe(1)`,
		},
		...[
			`function loaded<T>(value: T | null): T { if (!value) throw new Error("not loaded"); return value }`,
			`test("x", () => { let fail = () => { throw new Error("kaboom") } })`,
			`test("x", () => { function helper() { throw new Error("x") } })`,
			`describe("x", () => { function helper() { throw new Error("x") } })`,
		].map(code => ({ name: code, code })),
	],
	invalid: [
		...invalid("disallowedMatcher", [
			`expect(1).toBe(1)`,
			`expect(1).toEqual(1)`,
			`expect(1).toSatisfy(value => value)`,
			`expect(1).toBeCorrect(1)`,
			`expect("a").toMatch(/a/)`,
			`expect(note).toMatchSnapshot({ id: anyString })`,
			`expect.soft(1).toBe(1)`,
			`await expect.soft(p).resolves.toEqual(1)`,
			`await expect.poll(() => count).toBe(1)`,
			`await expect(p).rejects.toBeInstanceOf(Error)`,
			`expect(1).toBe.call(null, 1)`,
			`import { expect as check } from "vitest"; check(1).toBe(1)`,
			`import { expect } from "vitest"; export function check(a: number, b: number) { expect(a).toBe(b) }`,
		]),
		...invalid("negatedMatcher", [
			`expect(() => run()).not.toThrow()`,
			`await expect(p).resolves.not.toThrow()`,
			`expect(1).not.toMatchInlineSnapshot()`,
		]),
		...invalid("missingMatcher", [
			`expect(1)`,
			`expect(1).not`,
			`let assertion = expect(1); assertion.toBe(1)`,
			`expect(1).toMatchInlineSnapshot`,
		]),
		...invalid("propertyMatchers", [
			`expect(note).toMatchInlineSnapshot({ id: anyString }, \`{}\`)`,
			`expect(note).toMatchInlineSnapshot({})`,
			`expect(note).toMatchInlineSnapshot(matchers, \`{}\`)`,
		]),
		...invalid("dynamicSnapshot", [
			`expect(name).toMatchInlineSnapshot(name)`,
			`expect(name).toMatchInlineSnapshot(\`"\${name}"\`)`,
			`expect(name).toMatchInlineSnapshot(String(name))`,
			`expect(() => run()).toThrowErrorMatchingInlineSnapshot(\`\${message}\`)`,
		]),
		...invalid("expectAlias", [
			`let check = expect; check(1).toBe(1)`,
			`let check = { check: expect }`,
			`let check = () => expect`,
			`helper(expect)`,
			`let soft = expect.soft; soft(1).toBe(1)`,
			`import { expect } from "vitest"; export { expect as check }`,
			`(expect as any)(1).toBe(1)`,
		]),
		...invalid("disallowedExpectMember", [
			`expect.call(null, 1).toBe(1)`,
			`expect.apply(null, [1]).toBe(1)`,
			`expect.bind(null)(1)`,
			`expect.any(String)`,
			`expect.objectContaining({ id: 1 })`,
			`expect.unreachable()`,
			`expect.getState()`,
		]),
		...invalid("setupOnly", [
			`expect.extend({ toBeFine: () => ({ pass: true, message: () => "" }) })`,
			`expect.addSnapshotSerializer({ test: () => true, serialize: () => "ok" })`,
			`expect.addEqualityTesters([])`,
		]),
		...invalid("zeroAssertions", [
			`expect.assertions(0)`,
			`expect.assertions(count)`,
			`expect.assertions()`,
		]),
		...invalid("assertionProperty", [
			`framework.expect(1).toMatchInlineSnapshot()`,
			`test("x", ctx => { ctx.expect(1).toBe(1) })`,
			`test("x", ({ expect }) => { expect(1).toBe(1) })`,
			`test("x", ({ expect: check }) => { check(1).toBe(1) })`,
			`let { expect: check } = framework`,
			`globalThis.expect(1).toBe(1)`,
			`globalThis["expect"](1).toBe(1)`,
			`vi.assert(true)`,
			`value.should.equal(1)`,
		]),
		...invalid("assertStyle", [
			`assert(value)`,
			`assert.equal(1, 1)`,
			`let check = assert; check.equal(1, 1)`,
			`chai.use(plugin)`,
			`import assert from "assert"`,
			`import assert from "node:assert"`,
			`import { strict } from "node:assert"`,
			`import * as assert from "node:assert/strict"`,
			`import { assert } from "vitest"`,
			`import { assert as check } from "vitest"`,
			`import { chai } from "vitest"`,
			`import { should } from "vitest"`,
			`import { expect } from "chai"`,
			`import chai from "chai"`,
			`import { expect } from "@vitest/expect"`,
			`await import("chai")`,
			`await import("node:assert")`,
			`await import("assert")`,
			`require("chai")`,
		]),
		...invalid("disallowedVitestExport", [
			`import { createExpect } from "vitest"`,
		]),
		...invalid("vitestNamespace", [
			`import * as framework from "vitest"`,
			`import framework from "vitest"`,
		]),
		...invalid("moduleLoad", [
			`let { describe } = await import("vitest")`,
			`await vi.importActual("vitest")`,
			`import framework = require("vitest")`,
		]),
		...invalid("dynamicModule", [
			`await import(name)`,
			`await import("vi" + "test")`,
			`await vi.importActual(name)`,
		]),
		...invalid("reexport", [
			`export * from "vitest"`,
			`export { expect as check } from "vitest"`,
			`export { assert } from "chai"`,
		]),
		{
			name: "a property of a dynamically imported vitest",
			code: `(await import("vitest")).expect(1).toBe(1)`,
			errors: [{ messageId: "assertionProperty" }, { messageId: "moduleLoad" }],
		},
		...invalid("throwInTest", [
			`test("x", () => { throw new Error("x") })`,
			`test("x", async () => { if (!value) throw new Error("x") })`,
			`it("x", function () { throw new Error("x") })`,
			`it.only("x", () => { throw new Error("x") })`,
			`test.each([1])("x %s", () => { throw new Error("x") })`,
			`test("x", () => { for (let item of items) { if (item) throw new Error("x") } })`,
			`beforeEach(() => { throw new Error("x") })`,
			`afterAll(async () => { throw new Error("x") })`,
		]),
	],
})
